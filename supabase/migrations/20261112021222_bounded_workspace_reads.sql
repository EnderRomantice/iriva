CREATE TABLE iriva.workspace_revisions (name text PRIMARY KEY, generation bigint NOT NULL DEFAULT 0);
ALTER TABLE iriva.workspace_revisions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON iriva.workspace_revisions FROM PUBLIC;
GRANT SELECT ON iriva.workspace_revisions TO iriva_runtime;
CREATE POLICY runtime_revision_read ON iriva.workspace_revisions FOR SELECT TO iriva_runtime USING (true);
CREATE FUNCTION iriva.bump_workspace_revision() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
 UPDATE iriva.workspace_revisions SET generation=generation+1 WHERE name=TG_TABLE_NAME;
 RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION iriva.bump_workspace_revision() FROM PUBLIC;
