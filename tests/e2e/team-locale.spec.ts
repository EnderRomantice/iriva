import { test, expect } from '@playwright/test';
import { createHash, randomBytes } from 'node:crypto';
import postgres from 'postgres';
import { seedId } from '../../server/db/seed';

test('home language persists through sign-in and team tabs; switching preserves edits', async ({ browser }) => {
  if (process.env.PG_LOCAL_TEST !== '1' || !process.env.DATABASE_URL) throw new Error('Use the disposable PostgreSQL harness.');
  const db = postgres(process.env.DATABASE_URL, { max: 1, ssl: false });
  const context = await browser.newContext();
  const origin = 'http://127.0.0.1:3117';
  const page = await context.newPage();
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(`${origin}/`);
    await page.getByRole('button', { name: '选择语言', exact: true }).click();
    await page.getByRole('button', { name: 'English', exact: true }).click();
    await expect(page).toHaveURL(`${origin}/en`);
    await page.goto(`${origin}/team/signin`);
    await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeVisible();
    const token = randomBytes(32).toString('hex');
    await db`INSERT INTO iriva.auth_sessions (token_hash,user_id,expires_at,auth_method) VALUES (${createHash('sha256').update(token).digest('hex')},${seedId(6)},${Date.now()+3600000},'password')`;
    await context.addCookies([{ name: 'iriva_session', value: token, url: origin, httpOnly: true, sameSite: 'Lax' }]);
    await page.goto(`${origin}/team`);
    await expect(page.getByRole('heading', { name: 'Activity reviews', exact: true })).toBeVisible();
    await expect(page.locator('html')).toHaveAttribute('lang', 'en');
    for (const label of ['Applications', 'Create a household', 'Households', 'Feedback', 'Team tasks', 'Organization & members', 'Audit log', 'Host management']) {
      await page.getByRole('button', { name: label, exact: true }).click();
      await expect(page.getByRole('heading', { name: label, exact: true })).toBeVisible();
    }
    await page.getByLabel('Host name', { exact: true }).fill('保留原文 Emma');
    await page.getByRole('button',{name:'Choose language',exact:true}).click();
    await page.getByRole('button',{name:'简体中文',exact:true}).click();
    await expect(page.getByRole('heading', { name: 'Host 管理', exact: true })).toBeVisible();
    await expect(page.getByLabel('Host 姓名', { exact: true })).toHaveValue('保留原文 Emma');
    await page.getByRole('button',{name:'选择语言',exact:true}).click();
    await page.getByRole('button',{name:'English',exact:true}).click();
    await expect(page.getByLabel('Host name', { exact: true })).toHaveValue('保留原文 Emma');
    await page.reload();
    await expect(page.getByRole('heading', { name: 'Activity reviews', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Team tasks', exact: true }).click();
    await page.getByLabel('Task description').fill('Locale regression task');
    await page.getByRole('button',{name:'Choose language',exact:true}).click();
    await page.getByRole('button',{name:'简体中文',exact:true}).click();
    await expect(page.getByLabel('待办内容')).toHaveValue('Locale regression task');
    await page.getByRole('button', { name: '添加', exact: true }).click();
    await expect(page.getByText('Locale regression task', { exact: true })).toBeVisible();
    await page.getByRole('button',{name:'选择语言',exact:true}).click();
    await page.getByRole('button',{name:'English',exact:true}).click();
    await expect(page.getByRole('status')).toHaveText('Saved.');
    await expect(page.getByText('Locale regression task', { exact: true })).toBeVisible();
    const created=await context.request.post(`${origin}/api/team/organizations`,{headers:{origin},data:{action:'create',name:'Second team'}});
    expect(created.ok()).toBe(true);
    await page.reload();
    const switcher=page.getByRole('button',{name:'Switch organization',exact:true});
    await switcher.click();
    await expect(page.getByRole('menu')).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(switcher).toBeFocused();
    await expect(switcher).toHaveAttribute('aria-expanded','false');
    await switcher.click();
    await page.getByRole('heading',{name:'Activity reviews',exact:true}).click();
    await expect(switcher).toHaveAttribute('aria-expanded','false');
    await switcher.click();
    await page.getByRole('menuitemradio',{name:/Second team/}).click();
    await expect(switcher).toContainText('Second team');
    await expect(page.locator('html')).toHaveAttribute('lang','en');
    await switcher.click();
    await expect(switcher).toHaveAttribute('aria-expanded','true');
    await expect.poll(()=>page.getByRole('menu').evaluate(el=>getComputedStyle(el).opacity)).toBe('1');
    await page.screenshot({path:'test-results/team-locale.png',fullPage:true});
    await page.keyboard.press('Escape');
    await page.setViewportSize({width:390,height:844});
    await switcher.click();
    await expect(page.getByRole('menuitemradio',{name:/Second team/})).toBeVisible();
    await expect.poll(()=>page.getByRole('menu').evaluate(el=>getComputedStyle(el).opacity)).toBe('1');
    await page.screenshot({path:'test-results/team-locale-mobile.png',fullPage:true});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
    expect(errors).toEqual([]);
  } finally { await context.close(); await db.end(); }
});
